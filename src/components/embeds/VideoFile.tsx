/**
 * The public renderer for the `videoFile` block: a video the newsroom uploaded, played from
 * our own object storage.
 *
 * DELIBERATELY NOT A CLIENT COMPONENT, and deliberately not the click-to-load facade its
 * sibling `MediaEmbed` uses. That facade exists to stop a THIRD PARTY from running scripts
 * and setting cookies on our reader before they have asked to watch anything; there is no
 * third party here, and `<video controls>` is a native element that already gives the reader
 * play, scrub, volume, fullscreen, picture-in-picture, keyboard access and their platform's
 * own captions UI. Wrapping that in a React facade would ship JavaScript to re-implement,
 * worse, what the browser does for free.
 *
 * THE COST CONTROL IS `preload`, NOT JAVASCRIPT. With a poster the element is told to fetch
 * NOTHING (`preload="none"`), so an article carrying a 72 MB video costs a reader who never
 * presses play exactly the bytes of one JPEG. Without a poster the browser has no frame to
 * draw and would otherwise show a black rectangle, so it is allowed to fetch metadata only —
 * the `moov` atom and a first frame, kilobytes rather than megabytes, and only because the
 * alternative is an article with a hole in it. The block's own field description pushes the
 * journalist towards supplying a poster for exactly this reason.
 *
 * THE BOX IS RESERVED BEFORE THE VIDEO LOADS, AND THE POSTER IS WHAT SIZES IT. A `media`
 * document for a VIDEO carries no width or height — sharp never sees it — so the renderer
 * cannot ask the clip what shape it is without downloading it, which is the one thing
 * `preload="none"` exists to avoid. But the poster is an IMAGE, Payload does record its
 * dimensions, and a poster is a frame of the video: its aspect ratio is the video's aspect
 * ratio. So when there is a poster the box is given exactly the right shape up front, and
 * nothing moves when the metadata finally arrives.
 *
 * This matters because of what this newsroom actually receives. A clip handed over on
 * WhatsApp is as often portrait as landscape, and a 9:16 video letterboxed into a fixed 16:9
 * box is a thin strip between two black slabs — correct, stable and ugly. Without a poster
 * there is nothing to measure, so 16:9 remains the fallback: a guess that is stable is still
 * better than a reflow, which is the same trade the article header makes in `VideoPlayer.tsx`
 * for the same reason.
 *
 * `maxHeight` is the bound on that. A very tall portrait at full column width would otherwise
 * reserve more than a screen of height; clamped, it letterboxes inside a screen-sized box
 * instead, which is what every social player does with the same material.
 */

/**
 * The block's stored fields, read defensively.
 *
 * NOT the generated `VideoFileBlock` type, for the reason given at the top of
 * `RichTextBody.tsx`: a generated type describes today's schema, and this function is handed
 * rows written by whatever version of the block was deployed when the article was saved.
 * Everything is optional and everything is checked.
 */
type MediaLike = {
  url?: string | null
  mimeType?: string | null
  filename?: string | null
  alt?: string | null
  width?: number | null
  height?: number | null
}

/** Populated by Payload at `depth >= 1`; an unpopulated relationship is just an id. */
function asMedia(value: unknown): MediaLike | null {
  if (!value || typeof value !== 'object') return null
  const candidate = value as MediaLike
  return typeof candidate.url === 'string' && candidate.url.trim() !== '' ? candidate : null
}

/**
 * A media URL we are willing to put in a `src`.
 *
 * These URLs are generated by the storage adapter from a document WE created, not typed by
 * an editor, so this is a backstop rather than the primary control — but it is a cheap one,
 * and it is the only thing standing between a corrupted or hand-edited `media.url` row and
 * a `javascript:`/`data:` URL in an attribute on a public page. Same posture as
 * `safeExternalHref` in `embed-ui.ts`, narrowed to the two shapes our own storage produces:
 * a site-relative path (local disk in dev) or an absolute https URL (Blob / R2).
 */
export function safeMediaSrc(url: string | null | undefined): string | null {
  if (typeof url !== 'string') return null
  const trimmed = url.trim()
  if (trimmed === '') return null
  if (trimmed.startsWith('/') && !trimmed.startsWith('//')) return trimmed
  try {
    return new URL(trimmed).protocol === 'https:' ? trimmed : null
  } catch {
    return null
  }
}

/**
 * The poster's shape as a CSS `aspect-ratio`, or null when it cannot be measured.
 *
 * Deliberately strict: a zero, a negative, a non-finite or a missing dimension all mean "we
 * do not know", and guessing from half a measurement would reserve the wrong box — worse
 * than falling back to 16:9, because a wrong reserved box cannot be corrected without the
 * reflow this is here to prevent.
 */
export function posterAspectRatio(media: { width?: number | null; height?: number | null } | null): string | null {
  const width = media?.width
  const height = media?.height
  if (typeof width !== 'number' || typeof height !== 'number') return null
  if (!Number.isFinite(width) || !Number.isFinite(height)) return null
  if (width <= 0 || height <= 0) return null
  return `${width} / ${height}`
}

export function VideoFile({
  video,
  poster,
  caption,
}: {
  video: unknown
  poster?: unknown
  caption?: string | null
}) {
  const media = asMedia(video)
  const src = safeMediaSrc(media?.url)

  // The shape of a block an editor is still filling in — or one whose media document was
  // deleted out from under it. An empty 16:9 box with a caption under it reads to a reader
  // as a broken page; saying nothing is the honest degradation. Same rule as `MediaEmbed`.
  if (!src) return null

  const posterMedia = asMedia(poster)
  const posterSrc = safeMediaSrc(posterMedia?.url)
  const ratio = posterSrc ? posterAspectRatio(posterMedia) : null
  const visibleCaption = typeof caption === 'string' && caption.trim() ? caption.trim() : null
  const type = typeof media?.mimeType === 'string' && media.mimeType.startsWith('video/')
    ? media.mimeType
    : undefined

  return (
    <figure data-testid="lf-video-file" className="my-6">
      <div
        className={`relative w-full overflow-hidden rounded-xl bg-brand-900${ratio ? '' : ' aspect-video'}`}
        style={ratio ? { aspectRatio: ratio, maxHeight: '80vh' } : undefined}
      >
        <video
          // `controls` is what makes this keyboard- and screen-reader-operable without a
          // line of our own JavaScript.
          controls
          // iOS Safari otherwise hijacks playback into its own fullscreen player, which
          // takes the reader out of the article.
          playsInline
          preload={posterSrc ? 'none' : 'metadata'}
          poster={posterSrc ?? undefined}
          aria-label={visibleCaption ?? 'فيديو داخل المقال'}
          className="absolute inset-0 h-full w-full object-contain"
        >
          <source src={src} type={type} />
          {/* Reached only by a browser that cannot play the container at all. Handing over
              the file beats a blank element with no explanation. */}
          <a href={src} download>
            متصفحك لا يستطيع تشغيل هذا الفيديو. اضغط هنا لتحميله.
          </a>
        </video>
      </div>
      {visibleCaption && (
        <figcaption className="mt-2 text-sm leading-relaxed text-brand-700">{visibleCaption}</figcaption>
      )}
    </figure>
  )
}
